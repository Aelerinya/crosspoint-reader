#pragma once

#include <BookSender.h>

#include <cstddef>
#include <cstdint>
#include <memory>
#include <string>
#include <vector>

// Adds a bookplate page to an EPUB while it is being sent to another reader.
// See README.md. Plain C++ (no Arduino) so the host tests can run it.

// Random access to the original EPUB (a file on the SD card, or memory in tests).
class BookplateInput {
 public:
  virtual ~BookplateInput() = default;
  virtual uint32_t size() const = 0;
  // Reads exactly `len` bytes at `offset`, or fails.
  virtual bool readAt(uint32_t offset, uint8_t* buf, size_t len) = 0;
};

struct BookplateContent {
  std::string title;  // book title as shown on the plate
  std::string from;   // sender's name (signature)
  std::string date;   // e.g. "8 November 2026"; empty when the clock is unknown
  // PNG of the generated page; empty for the text-only style.
  std::vector<uint8_t> png;
};

// Files the bookplate adds next to the OPF. Fixed names, so a re-sent book's
// old bookplate is found and replaced.
namespace bookplate {
constexpr const char* XHTML_NAME = "x4c-bookplate.xhtml";
constexpr const char* PNG_NAME = "x4c-bookplate.png";
constexpr const char* XHTML_ID = "x4c-bookplate";
constexpr const char* PNG_ID = "x4c-bookplate-img";

// The page: the image (when there is one) then the same words as text.
std::string xhtml(const BookplateContent& content);
// Returns the OPF with any old bookplate removed and the new one added to the
// manifest and to the spine (after a leading cover page, else first).
// Empty when the OPF has no <manifest> or <spine>.
std::string patchOpf(const std::string& opf, bool withImage);
// 1-bit grayscale PNG (stored deflate). `rows`: h rows of `stride` bytes,
// MSB first, bit set = white.
std::vector<uint8_t> encodePng1(const uint8_t* rows, int w, int h, int stride);
std::string xmlEscape(const std::string& text);
// `text` without invalid UTF-8 (truncated sequences, surrogates...) and XML-illegal controls.
std::string validUtf8(const std::string& text);
// The first <dc:title> of an OPF, entities decoded, whitespace collapsed.
std::string opfTitle(const std::string& opf);
}  // namespace bookplate

// The rewritten EPUB as a stream of known size: original zip entries copied
// byte for byte (compressed data untouched), the OPF replaced by a stored
// patched copy, the bookplate files appended, and a new central directory.
class BookplateEpub final : public BookSendSource {
 public:
  BookplateEpub();
  ~BookplateEpub() override;
  // Reads the zip index and the OPF. False (with `error`) when the book cannot
  // take a bookplate (not a zip, ZIP64, no OPF, sizes past the limits): send
  // the original file instead.
  bool open(BookplateInput& input, std::string* error = nullptr);
  // After open(): the book's title from its OPF ("" if none).
  std::string title() const;
  // After open(): the biggest single block and the total heap prepare() needs
  // for a PNG of `pngSize` bytes, to check against the free heap first.
  size_t largestAllocation(size_t pngSize) const;
  size_t memoryNeeded(size_t pngSize) const;
  // After open(): plans the rewrite (the zip index is freed afterwards).
  bool prepare(const BookplateContent& content, std::string* error = nullptr);
  uint32_t size() const { return totalSize; }
  // Sequential read of the rewritten EPUB (BookSendSource).
  int read(uint8_t* buf, size_t len) override;

 private:
  struct Segment {
    bool fromInput;
    uint32_t offset;  // input offset, or offset into `memory`
    uint32_t length;
  };
  struct Index;
  std::unique_ptr<Index> index;  // between open() and prepare()
  BookplateInput* input = nullptr;
  std::vector<uint8_t> memory;  // generated bytes (headers, OPF, page, central dir)
  std::vector<Segment> segments;
  uint32_t totalSize = 0;
  size_t segIndex = 0;
  uint32_t segPos = 0;

  void addInput(uint32_t offset, uint32_t length);
  void addMemory(const uint8_t* data, size_t length);
};
